import fs from 'node:fs';
import path from 'node:path';
import ts from 'typescript';

const root = process.cwd();
const sourcePath = path.join(root, 'src/game/recommendation/recommendation-engine.ts');
const outPath = path.join(root, 'public/game/recommendation_engine.js');

const compiled = ts.transpileModule(fs.readFileSync(sourcePath, 'utf8'), {
  compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2019, strict: true, esModuleInterop: true },
  fileName: sourcePath,
}).outputText;

const bundle = `// Generated by scripts/build-browser-recommendation-engine.mjs. Do not edit manually.
(function(global){
  var module={exports:{}};
  var exports=module.exports;
${compiled}
  global.WannianRecommendationEngine = module.exports;
})(typeof window !== 'undefined' ? window : globalThis);
`;

fs.writeFileSync(outPath, bundle, 'utf8');
console.log(`Built ${path.relative(root, outPath)} from src/game/recommendation/recommendation-engine.ts`);
