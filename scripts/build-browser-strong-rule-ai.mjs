import fs from 'node:fs';
import path from 'node:path';
import ts from 'typescript';

const root = process.cwd();
const rulesDir = path.join(root, 'src/game/rules');
const strongDir = path.join(root, 'src/game/strong-rule-ai');
const outPath = path.join(root, 'public/game/strong_rule_ai.js');

function compile(filePath) {
  return ts.transpileModule(fs.readFileSync(filePath, 'utf8'), {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2019, strict: true, esModuleInterop: true },
    fileName: filePath,
  }).outputText;
}

function filesFor(dir) {
  return fs.readdirSync(dir).filter((name) => name.endsWith('.ts')).sort((a, b) => {
    if (a === 'index.ts') return 1;
    if (b === 'index.ts') return -1;
    return a.localeCompare(b);
  });
}

const moduleEntries = [];
for (const file of filesFor(rulesDir)) moduleEntries.push({ id: `../rules/${file.replace(/\.ts$/, '')}`, filePath: path.join(rulesDir, file) });
for (const file of filesFor(strongDir)) moduleEntries.push({ id: `./${file.replace(/\.ts$/, '')}`, filePath: path.join(strongDir, file) });

function factory(entry) {
  return `${JSON.stringify(entry.id)}: function(require, module, exports) {\n${compile(entry.filePath)}\n}`;
}

const bundle = `// Generated by scripts/build-browser-strong-rule-ai.mjs. Do not edit manually.\n(function(global){\n  var factories = {\n${moduleEntries.map(factory).join(',\n')}\n  };\n  var cache = {};\n  function dirname(id){ var i=id.lastIndexOf('/'); return i>=0?id.slice(0,i):'.'; }\n  function normalizePath(path){\n    var parts=[];\n    path.split('/').forEach(function(part){ if(!part||part==='.'){return;} if(part==='..'){parts.pop();} else parts.push(part); });\n    return (path.indexOf('../')===0?'../':'./') + parts.filter(function(part){return part!=='.';}).join('/').replace(/^\\.\\//,'');\n  }\n  function resolve(request,parent){\n    if(request==='../rules' || request==='../rules/index') return '../rules/index';\n    if(request.indexOf('../rules/')===0) return request;\n    if(request.indexOf('./')===0){\n      var base=dirname(parent||'./index');\n      var raw=(base==='.'?'':base+'/')+request;\n      var resolved=normalizePath(raw);\n      if(factories[resolved]) return resolved;\n      if(factories[resolved+'/index']) return resolved+'/index';\n    }\n    if(factories[request]) return request;\n    throw new Error('Cannot find strong AI module '+request+' from '+parent);\n  }\n  function localRequire(request,parent){\n    var id=resolve(request,parent);\n    if(!cache[id]){ var module={exports:{}}; cache[id]=module; factories[id](function(next){return localRequire(next,id);},module,module.exports); }\n    return cache[id].exports;\n  }\n  global.WannianStrongRuleAI = localRequire('./index','./index');\n})(typeof window !== 'undefined' ? window : globalThis);\n`;

fs.writeFileSync(outPath, bundle, 'utf8');
console.log(`Built ${path.relative(root, outPath)} from ${moduleEntries.length} modules`);
