import fs from 'node:fs';
import path from 'node:path';
import ts from 'typescript';

const root = process.cwd();
const sourceDir = path.join(root, 'src/game/rules');
const outPath = path.join(root, 'public/game/rule_engine.js');
const moduleFiles = fs.readdirSync(sourceDir).filter((name) => name.endsWith('.ts')).sort((a, b) => {
  if (a === 'index.ts') return 1;
  if (b === 'index.ts') return -1;
  return a.localeCompare(b);
});

function normalizeId(fileName) {
  return `./${fileName.replace(/\.ts$/, '')}`;
}

function compile(fileName) {
  const filePath = path.join(sourceDir, fileName);
  return ts.transpileModule(fs.readFileSync(filePath, 'utf8'), {
    compilerOptions: {
      module: ts.ModuleKind.CommonJS,
      target: ts.ScriptTarget.ES2019,
      strict: true,
      esModuleInterop: true,
    },
    fileName: filePath,
  }).outputText;
}

const modules = moduleFiles.map((fileName) => {
  const id = normalizeId(fileName);
  return `${JSON.stringify(id)}: function(require, module, exports) {\n${compile(fileName)}\n}`;
}).join(',\n');

const bundle = `// Generated by scripts/build-browser-rule-engine.mjs. Do not edit manually.\n(function(global){\n  var factories = {\n${modules}\n  };\n  var cache = {};\n  function normalize(request) {\n    return request.indexOf('./') === 0 ? request : './' + request;\n  }\n  function localRequire(request) {\n    var id = normalize(request);\n    if (!factories[id]) throw new Error('Cannot find rule module ' + request);\n    if (!cache[id]) {\n      var module = { exports: {} };\n      cache[id] = module;\n      factories[id](localRequire, module, module.exports);\n    }\n    return cache[id].exports;\n  }\n  global.WannianRuleEngine = localRequire('./index');\n})(typeof window !== 'undefined' ? window : globalThis);\n`;

if (process.argv.includes('--check')) {
  const currentBundle = fs.existsSync(outPath) ? fs.readFileSync(outPath, 'utf8') : null;
  if (currentBundle !== bundle) throw new Error(`Browser rule engine does not match current rules source: ${path.relative(root, outPath)}`);
  console.log(`Verified ${path.relative(root, outPath)} matches current rules source`);
  process.exit(0);
}

fs.writeFileSync(outPath, bundle, 'utf8');
console.log(`Built ${path.relative(root, outPath)} from ${moduleFiles.length} rule modules`);
